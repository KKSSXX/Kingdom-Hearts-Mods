		stmgames = 1
		ConsolePrint("Keyblade Stats (Steam GL) - installed")
	end
	
	if ReadLong(IsSteamJPVersion) == 0x7265737563697065 and stmjpgames == 0 then
		stmjpgames = 1
		ConsolePrint("Keyblade Stats (Steam JP) - installed")
